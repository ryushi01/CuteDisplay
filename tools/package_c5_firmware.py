#!/usr/bin/env python3
"""Bundle a separately compiled ESP32-C5 app binary into the S3 sketch.

One-time bootstrap: flash OTA-capable C5 sketch by its own USB.
Future upgrades: change C5FirmwareVersion.h, compile C5 to .bin, run
this script, and upload the S3 sketch containing C5FirmwareImage.h.
Only Python standard library is needed.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
VERSION_HEADER = ROOT / "firmware/CuteDisplay/C5FirmwareVersion.h"
DEST = ROOT / "firmware/CuteDisplayBrain/C5FirmwareImage.h"
MAX_SLOT = 0x640000  # default_16MB.csv inactive OTA slot, 6.25 MiB

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bin", required=True, type=Path, help="Compiled ESP32-C5 *application* .bin")
    ap.add_argument("--version", required=True, type=int, help="Matches C5FirmwareVersion.h")
    ap.add_argument("--output", type=Path, default=DEST)
    args = ap.parse_args()
    source = VERSION_HEADER.read_text(encoding="utf-8")
    match = re.search(r"\bC5_FIRMWARE_VERSION\s*=\s*(\d+)\s*;", source)
    if not match:
        ap.error(f"No C5_FIRMWARE_VERSION found in {VERSION_HEADER}")
    source_version = int(match.group(1))
    if args.version != source_version:
        ap.error(f"Image v{args.version} doesn't match C5 source v{source_version}; "
                 "edit C5FirmwareVersion.h and rebuild C5 before packaging")
    if not 1 < args.version < 2**32:
        ap.error("The bootstrap display firmware is v1; bundle v2 or higher")
    raw = args.bin.read_bytes()
    if len(raw) < 1024 or len(raw) > MAX_SLOT:
        ap.error(f"C5 firmware length {len(raw)} is invalid; inactive slot max {MAX_SLOT}")
    if raw[0] != 0xE9:
        ap.error("The input is not an ESP32 app image (missing image magic 0xE9)")
    # ESP image 8-byte header + extended-header 4-byte flash settings;
    # chip ID is little-endian bytes 12-13. ESP32-C5 has chip ID 0x0017.
    chip_id = int.from_bytes(raw[12:14], "little")
    if chip_id != 0x0017:
        ap.error(f"Incorrect binary chip ID {chip_id}: expected ESP32-C5 (23)")
    digest = hashlib.sha256(raw).hexdigest()
    dest = args.output.resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)
    with dest.open("w", encoding="ascii", newline="\n") as file:
        file.write("#pragma once\n#include <Arduino.h>\n")
        file.write("// AUTOGENERATED: do not edit. Compiled ESP32-C5 application ONLY.\n")
        file.write("namespace C5Image {\n")
        file.write(f"inline constexpr uint32_t version={args.version}UL;\n")
        file.write(f"inline constexpr size_t length={len(raw)}UL;\n")
        file.write(f'inline constexpr char sha256[]="{digest}";\n')
        file.write("static const uint8_t bytes[] PROGMEM={\n")
        for start in range(0, len(raw), 32):
            file.write("  " + ",".join(f"0x{x:02X}" for x in raw[start:start + 32]) + ",\n")
        file.write("};\n}\n")
    print(f"Packaged C5 v{args.version}, {len(raw)} bytes, SHA256 {digest}")
    print(f"Output: {dest}")
    print("NEXT: Compile/upload ONLY the S3 Brain sketch; ensure S3 app fits its flash partition.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
