#!/usr/bin/env python3
"""Generate compact Japanese 16x16 bitmap fallback font for C5.
Uses locally installed Noto Sans CJK JP (OFL). Font file itself isn't distributed.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageFont, ImageDraw

def repertoire():
    chars=set()
    # JIS X 0208: hiragana, katakana, punctuation and all standard kanji.
    for hi in list(range(0x81,0xA0))+list(range(0xE0,0xF0)):
        for lo in range(0x40,0xFD):
            if lo==0x7F: continue
            try: c=bytes([hi,lo]).decode("cp932")
            except UnicodeDecodeError: continue
            if len(c)==1 and ord(c)>=128:
                chars.add(ord(c))
    # Western European text: precomposed French accents (é, è, ê, ë,
    # à, â, î, ï, ô, ù, û, ü, ç, œ, æ, ÿ), extended Latin, and phonetics.
    chars.update(range(0x00A0,0x0250))
    chars.update(range(0x1E00,0x1F00))
    # Smart quotes, dashes, ellipses, currency, arrows and math symbols.
    # Include common symbols without depending on glyphs supplied by iOS.
    for start, end in (
        (0x2000,0x2070), (0x20A0,0x20D0), (0x2100,0x2150),
        (0x2190,0x2300), (0x2460,0x2500),
    ):
        chars.update(range(start,end))
    # Full BMP CJK Unified Ideographs and Extension A, so Japanese kanji
    # outside the smaller Shift-JIS/CP932 repertoire also have a fallback.
    # Bitmap data is stored in program flash (not runtime PSRAM).
    chars.update(range(0x3400,0xA000))
    chars.update(range(0xF900,0xFB00))  # CJK compatibility ideographs
    chars.update(range(0x3040,0x3100))  # Hiragana + Katakana
    chars.update(range(0x31F0,0x3200))  # Katakana phonetic extensions
    chars.update(range(0x3000,0x3040))  # Japanese punctuation
    chars.update(range(0xFF01,0xFFA0))  # Fullwidth / halfwidth forms
    return sorted(x for x in chars if x<=0xFFFF)

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--out",required=True)
    ap.add_argument("--font",default="/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
    args=ap.parse_args()
    fontfile=Path(args.font)
    if not fontfile.is_file():
        raise SystemExit("Missing Noto CJK JP font: "+str(fontfile))
    # TTC face 0 is JP in the common Linux Noto distribution.
    font=ImageFont.truetype(str(fontfile),16,index=0)
    cps=repertoire()
    out=Path(args.out)
    with out.open("w",encoding="utf-8") as f:
        f.write("#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n")
        f.write("// Generated by tools/generate_c5_japanese_font.py; Noto Sans CJK JP (OFL).\n")
        f.write(f"static constexpr uint32_t C5_JP_COUNT={len(cps)};\n")
        f.write("struct C5JPEntry {uint16_t cp; uint8_t bitmap[32];};\n")
        f.write("static const C5JPEntry C5JPFont[] PROGMEM={\n")
        for cp in cps:
            img=Image.new("L",(16,16),0)
            d=ImageDraw.Draw(img)
            # Anchor glyph to top/left with consistent 16px CJK advances.
            d.text((0,0),chr(cp),fill=255,font=font,anchor="lt")
            bits=[]
            for y in range(16):
                for xbase in (0,8):
                    v=0
                    for dx in range(8):
                        if img.getpixel((xbase+dx,y))>=115:v|=0x80>>dx
                    bits.append(v)
            f.write("{"+str(cp)+",{"+",".join(str(v) for v in bits)+"}},\n")
        f.write("};\n")
        f.write("""inline const C5JPEntry *c5JPFind(uint32_t cp){
 if(cp>0xFFFF)return nullptr;
 int low=0,high=(int)C5_JP_COUNT-1;
 while(low<=high){
  int mid=low+(high-low)/2;
  uint16_t id=pgm_read_word(&C5JPFont[mid].cp);
  if(id==cp)return &C5JPFont[mid];
  if(id<cp)low=mid+1;else high=mid-1;
 }
 return nullptr;
}
""")
    print(f"Generated {len(cps)} Japanese glyphs in {out} ({out.stat().st_size} source bytes)")

if __name__=="__main__":main()
